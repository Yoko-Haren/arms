    # ------------------------------------------------------------------ making the copies stand alone
    def routes(self):
        """Which exported file stands for which address."""
        exact, by_path = {}, {}
        for page in self.pages:
            target = f"{page['group']}/{page['slug']}.html"
            exact.setdefault(page['full_url'], target)
            if page['group'] != 'auth' or page['slug'] in ('sign-in', 'forgot-1-account'):
                by_path.setdefault((page['group'], page['url']), target)
                by_path.setdefault((None, page['url']), target)
        patterns = [
            (re.compile(r'^/registrars/sections/\d+/$'), 'registrar/section-detail.html'),
            (re.compile(r'^/registrars/grades/class/\d+/period/\d+/$'), 'registrar/grade-review-ready.html'),
            (re.compile(r'^/admin-panel/schools/\d+/$'), 'admin/school-detail.html'),
            (re.compile(r'^/admin-panel/principals/\d+/$'), 'admin/principal-detail.html'),
            (re.compile(r'^/admin-panel/principals/\d+/edit/$'), 'admin/principal-edit.html'),
            (re.compile(r'^/accounts/(signout|logout)/$|^/admin-panel/logout/$'), 'auth/sign-in.html'),
            (re.compile(r'^/accounts/google/login/$'), 'auth/link-google-code.html'),
        ]
        return exact, by_path, patterns

    def localize(self, page, routes):
        exact, by_path, patterns = routes
        html = page['html']
        group = page['group']

        def resolve(url):
            if url in exact:
                return '../' + exact[url]
            path = url.split('?')[0].split('#')[0]
            # the same address differs per signed-in role (e.g. Account Settings): prefer this role's copy
            for key in ((group, path), (None, path)):
                if key in by_path:
                    return '../' + by_path[key]
            for pattern, target in patterns:
                if pattern.match(path):
                    return '../' + target
            return None

        def link(match):
            attr, quote, url = match.group(1), match.group(2), match.group(3).replace('&amp;', '&')
            if url.startswith('/static/'):
                return f'{attr}={quote}..{url}{quote}'
            target = resolve(url)
            if attr == 'action':
                return f'action={quote}#{quote}'
            return f'{attr}={quote}{target or "#"}{quote}'

        html = re.sub(r'\b(href|src|action)=(["\'])(/[^"\'>]*)\2', link, html)
        # address strings inside scripts
        html = html.replace('"/static/', '"../static/').replace("'/static/", "'../static/")
        for needle in ('"/accounts/google/login/"', "'/accounts/google/login/'"):
            html = html.replace(needle, '"../auth/link-google-code.html"')
        html = html.replace('"/accounts/password-reset/"', '"../auth/forgot-1-account.html"')

        banner = (f'<!-- ARMS static design copy: {page["title"]} ({page["full_url"]}). '
                  'Generated by `python manage.py export_screens`. -->\n')
        if page['inject']:
            html = re.sub(r'(<body[^>]*>)', lambda m: m.group(1) + '\n<script>\n' + page['inject'] + '\n</script>', html, count=1)
        html = html.replace('</body>', STATIC_NOTE + '</body>', 1) if '</body>' in html else html + STATIC_NOTE
        return banner + html
