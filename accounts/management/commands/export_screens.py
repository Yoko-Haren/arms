"""Export every live page, filled with the demo school's data, as static HTML for design work.

    python manage.py seed_demo         (once, if the demo school is not there yet)
    python manage.py export_screens    -> design/screens/

Each file is a faithful copy of the real page that opens straight from disk, so it can be
captured into Figma. Links between exported screens work, forms are switched off.
Nothing is saved to the database: the command signs in as the demo accounts inside a
transaction that is rolled back, and it never sends email.
"""
